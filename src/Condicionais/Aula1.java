package Condicionais;

public class Aula1 {

	public static void main(String[] args) {

		//IF, executa um codigo somente se a condicao for verdadeira
		
		
				int idade = 33;
				if( idade == 33) {
					
					System.out.println(idade);
				
					}
				
			//IF e ELSE
			//O else define o caminho alternativo quando a condicao do if nao é verdadeira.
				
				int notaFinal = 10;
				
				if(notaFinal < 100) {
					
					System.out.println("Reprovado");
					
					}else {
					
					System.out.println("Aprovado");
					
					}
	}

}
